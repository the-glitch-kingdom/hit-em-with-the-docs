/**
 * Locate facets in tracked code (#113): which files and lines hold the fact a facet names, so a draft can cite
 * them. One pass over `git ls-files`: each file is read once and every facet is tested per line (no spawn per
 * facet per file). Docs, archive, the cold root, reports and agent instruction files are not code; instruction
 * files are scanned apart, so a fact that lives only there can be reported as unreachable by search.
 * Only file and line come back, never the line text: a value must not leave the located file.
 */
import { execFileSync } from 'child_process';
import { readFile, stat } from 'fs/promises';
import { join, relative } from 'path';
import { compile_facet, is_weak_facet, match_facets } from './facets.js';

export interface FacetHit { file: string; line: number }
export interface LocateResult {
  /** Per facet (as given): hits in tracked code. Facets that do not compile are absent. */
  code: Map<string, FacetHit[]>;
  /** Per facet: hits in agent instruction files only. */
  instructions: Map<string, FacetHit[]>;
  /** Facets too short, numeric or broad to name code alone (#115): located only inside files the other facets found. */
  weak?: Set<string>;
}

/** Hits kept per facet: a draft cites a few lines; a facet matching hundreds is too generic to ground anything. */
export const MAX_HITS_PER_FACET = 20;
/** A facet matching more files than this is too broad to name code on its own (#115). */
export const WEAK_MAX_FILES = 10;
/** Hits kept for a weak facet inside the distinctive files. */
const MAX_WEAK_HITS = 200;
/** Larger files are generated or vendored, not hand-written code. */
const MAX_FILE_BYTES = 512 * 1024;
const NOT_CODE = /(^|\/)(node_modules|\.git|\.hewtd|\.planning|\.claude|dist)\/|^(reports|archive|build|coverage)\/|(^|\/)(\.gitleaksignore|\.gitleaks\.toml|\.secrets\.baseline|\.lint-baseline[^/]*|[^/]*baseline[^/]*\.json)$|(^|\/)(fixtures|__fixtures__|testdata|mocks|__mocks__|__snapshots__|mockups?)\/|^design\/|\.(snap|md|mdx|txt|rst|lock|map|min\.js|png|jpe?g|gif|ico|pdf|woff2?|zip|gz|svg)$|(^|\/)(package-lock\.json|pnpm-lock\.yaml|yarn\.lock)$/i;
/** Generated code is not hand-written: its first lines say so. */
const GENERATED = /@generated|do not edit|auto-?generated|generated by/i;
const INSTRUCTION = /(^|\/)(CLAUDE|AGENTS|GEMINI)\.md$|(^|\/)\.claude\/rules\/.+\.md$/;

export const is_instruction_file = (repo_path: string): boolean => INSTRUCTION.test(repo_path);

function list_tracked_files(repo_root: string): string[] {
  try {
    // eslint-disable-next-line id-denylist -- child_process option names
    return execFileSync('git', ['ls-files', '-z'], { cwd: repo_root, encoding: 'utf-8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] }).split('\0').filter(Boolean);
  } catch {
    return []; // not a git repo: nothing is tracked, so nothing is located
  }
}

async function read_code_file(repo_root: string, file: string): Promise<string | undefined> {
  try {
    const abs_path = join(repo_root, file);
    if ((await stat(abs_path)).size > MAX_FILE_BYTES) return undefined;
    const text = await readFile(abs_path, 'utf-8');
    if (text.slice(0, 8000).includes('\0')) return undefined; // binary
    return text;
  } catch {
    return undefined; // tracked but deleted in the working tree
  }
}

export async function locate_facets(options: { repo_root: string; docs_root: string; cold_root?: string; facets: string[]; /** Repo-relative files that are not code: the question set the facets came from lists them all. */ exclude_files?: string[] }): Promise<LocateResult> {
  const { repo_root, docs_root } = options;
  const compiled = options.facets.map((facet) => ({ facet, regex: compile_facet(facet).regex })).filter((item): item is { facet: string; regex: RegExp } => !!item.regex);
  const weak = new Set(compiled.filter(({ facet }) => is_weak_facet(facet)).map(({ facet }) => facet));
  const result: LocateResult = { code: new Map(compiled.map((item) => [item.facet, []])), instructions: new Map(compiled.map((item) => [item.facet, []])), weak };
  if (!compiled.length) return result;
  const docs_prefix = relative(repo_root, docs_root).split('\\').join('/') + '/';
  const cold_prefix = options.cold_root ? options.cold_root.replace(/^\.\//, '').replace(/\/?$/, '/') : undefined;
  const strong = compiled.filter(({ facet }) => !weak.has(facet));
  const files_by_facet = new Map(strong.map(({ facet }) => [facet, new Set<string>()]));
  // pass 1: distinctive facets across tracked files; every facet's file set is counted whole, its lines capped
  for (const file of list_tracked_files(repo_root)) {
    if (options.exclude_files?.includes(file)) continue;
    if (file.startsWith(docs_prefix) || (cold_prefix && file.startsWith(cold_prefix))) continue;
    const instruction = is_instruction_file(file);
    if (!instruction && NOT_CODE.test(file)) continue;
    if (!strong.length) break;
    const text = await read_code_file(repo_root, file);
    if (text === undefined) continue;
    if (!instruction && GENERATED.test(text.split('\n', 8).join('\n'))) continue;
    const into = instruction ? result.instructions : result.code;
    const matched = match_facets(strong.map(({ regex }) => regex), text.split('\n'), MAX_HITS_PER_FACET);
    strong.forEach(({ facet }, i) => {
      const found = into.get(facet)!;
      if (!matched[i]?.length) return;
      if (!instruction) files_by_facet.get(facet)!.add(file);
      for (const index of matched[i]!) if (found.length < MAX_HITS_PER_FACET) found.push({ file, line: index + 1 });
    });
  }
  // a facet matching too many files is weak for this run: its hits are dropped and it is re-located in pass 2
  for (const { facet } of strong) if (files_by_facet.get(facet)!.size > WEAK_MAX_FILES) { weak.add(facet); result.code.set(facet, []); }
  // pass 2: weak facets only inside the files the distinctive facets found
  const distinctive_files = [...new Set(strong.filter(({ facet }) => !weak.has(facet)).flatMap(({ facet }) => [...files_by_facet.get(facet)!]))].sort();
  const weak_facets = compiled.filter(({ facet }) => weak.has(facet));
  if (weak_facets.length && distinctive_files.length) {
    for (const file of distinctive_files) {
      const text = await read_code_file(repo_root, file);
      if (text === undefined) continue;
      const matched = match_facets(weak_facets.map(({ regex }) => regex), text.split('\n'), MAX_WEAK_HITS);
      weak_facets.forEach(({ facet }, i) => { for (const index of matched[i] ?? []) result.code.get(facet)!.push({ file, line: index + 1 }); });
    }
  }
  return result;
}
