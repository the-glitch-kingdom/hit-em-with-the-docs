import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { is_weak_facet } from '../../../src/core/coverage/facets.js';
import { locate_facets, WEAK_MAX_FILES } from '../../../src/core/coverage/locate.js';
import { resolve_decision, type DocText } from '../../../src/core/coverage/decide.js';
import { plan_coverage_misses } from '../../../src/core/coverage/plan.js';
import { load_plugin_config } from '../../../src/utils/config.js';

describe('is_weak_facet (#115 problem 4)', () => {
  it('short, numeric and punctuation-only facets are weak; words are not', () => {
    for (const weak of ['410', '200', '30\\.0', '\\b5\\b', 'ab', '^\\d+$', '[0-9]{3}']) expect(is_weak_facet(weak), weak).toBe(true);
    for (const strong of ['cache_ttl', 'CACHE_TTL\\b', 'retry_limit', 'purge\\s+cache', 'max_age']) expect(is_weak_facet(strong), strong).toBe(false);
  });
});

let repo: string;
const w = (p: string, t: string): void => { mkdirSync(join(repo, p, '..'), { recursive: true }); writeFileSync(join(repo, p), t); };
beforeAll(() => {
  repo = mkdtempSync(join(tmpdir(), 'distinct-'));
  w('src/gone.ts', 'export const GONE_STATUS = 410;\nexport const gone_message = 1;\n');
  for (let i = 0; i < WEAK_MAX_FILES + 5; i++) w(`src/many/f${i}.ts`, `const status = 410;\n${'// pad\n'.repeat(3)}const n${i} = 410;\n`);
  w('.gitleaksignore', 'GONE_STATUS 410\n');
  w('.secrets.baseline', 'GONE_STATUS 410\n');
  w('lint-baseline.json', '{"GONE_STATUS": 410}\n');
  w('.lint-baseline.json', '{"GONE_STATUS": 410}\n');
  w('tests/fixtures/f.ts', 'const GONE_STATUS = 410;\n');
  w('src/__fixtures__/g.ts', 'const GONE_STATUS = 410;\n');
  w('testdata/g.ts', 'const GONE_STATUS = 410;\n');
  w('mocks/g.ts', 'const GONE_STATUS = 410;\n');
  w('src/__snapshots__/a.snap', 'GONE_STATUS 410\n');
  w('design/mock.html', '<p>GONE_STATUS 410</p>\n');
  w('mockups/page.html', '<p>GONE_STATUS 410</p>\n');
  w('src/contract.ts', '// @generated by tool\nexport const GONE_STATUS = 410;\n');
  w('src/gen2.ts', '/* DO NOT EDIT */\nexport const GONE_STATUS = 410;\n');
  w('src/gen3.ts', '// Auto-generated file\nexport const GONE_STATUS = 410;\n');
  w('src/gen4.ts', '# generated by protoc\nGONE_STATUS = 410\n');
  w('.documentation/ops/gone.md', '---\ntitle: Gone\nsources:\n  - src/gone.ts\n---\n# Gone\n\nplain\n');
  execFileSync('git', ['init', '-q'], { cwd: repo });
  execFileSync('git', ['add', '-A'], { cwd: repo });
  execFileSync('git', ['-c', 'user.name=a', '-c', 'user.email=a@a', 'commit', '-qm', 'i'], { cwd: repo });
});
afterAll(() => rmSync(repo, { recursive: true, force: true }));
const docs_root = (): string => join(repo, '.documentation');

describe('two-pass locate (#115 problem 4)', () => {
  it('a numeric facet is located only inside files the distinctive facets found', async () => {
    const r = await locate_facets({ repo_root: repo, docs_root: docs_root(), facets: ['GONE_STATUS', '410'] });
    expect(r.code.get('GONE_STATUS')!.map((h) => h.file)).toEqual(['src/gone.ts']);
    expect(r.code.get('410')!.map((h) => h.file)).toEqual(['src/gone.ts']);
    expect(r.weak?.has('410')).toBe(true);
  });
  it('a facet matching more than WEAK_MAX_FILES files is weak too', async () => {
    const r = await locate_facets({ repo_root: repo, docs_root: docs_root(), facets: ['GONE_STATUS', 'const status'] });
    expect(r.weak?.has('const status')).toBe(true);
    expect(r.code.get('const status')).toEqual([]);
  });
  it('non-code files are never located: scanner allowlists, baselines, fixtures, snapshots, design, generated', async () => {
    const r = await locate_facets({ repo_root: repo, docs_root: docs_root(), facets: ['GONE_STATUS'] });
    expect([...new Set(r.code.get('GONE_STATUS')!.map((h) => h.file))]).toEqual(['src/gone.ts']);
  });
});

describe('decide with weak facets (#115 problem 4)', () => {
  const doc = (path: string, text: string, sources: string[] = []): DocText => ({ path, text, sources });
  it('weak hits outside the distinctive files do not become sources; a weak-only miss gets none and a note', () => {
    const code = new Map([['gone_message', [{ file: 'src/a.ts', line: 1 }]], ['410', [{ file: 'src/a.ts', line: 2 }, { file: 'src/z.ts', line: 3 }]]]);
    const d = resolve_decision({ key: 'q', query: 'q', count: 1, facets: ['gone_message', '410'] }, { code, instructions: new Map() }, []);
    expect(d.source_files).toEqual(['src/a.ts']);
    const only_weak = resolve_decision({ key: 'q', query: 'q', count: 1, facets: ['410'] }, { code: new Map([['410', [{ file: 'src/z.ts', line: 3 }]]]), instructions: new Map() }, []);
    expect(only_weak.sources).toEqual([]);
    expect(only_weak.notes.join(' ')).toMatch(/weak|distinctive/);
  });
  it('a weak facet does not make a citing doc the home', () => {
    const code = new Map([['410', [{ file: 'src/z.ts', line: 3 }]]]);
    const d = resolve_decision({ key: 'q', query: 'q', count: 1, facets: ['410', 'unheld_name'] }, { code, instructions: new Map() }, [doc('ops/z.md', 'x', ['src/z.ts'])]);
    expect(d.kind).toBe('new');
  });
});

describe('plan: no unrelated sources or reference hints (#115 problem 4)', () => {
  it('sources hold only files with a distinctive facet', async () => {
    const config = await load_plugin_config(repo);
    const r = await plan_coverage_misses({ repo_root: repo, docs_root: docs_root(), config, gaps: [{ query: 'what status for a removed item', used_doc: null, id: 'a', facets: ['gone_message', '410'] }], today: '2026-11-14' });
    expect(r.proposals[0]!.source_files).toEqual(['src/gone.ts']);
    expect(r.proposals[0]!.generated_reference).toEqual([]);
  });
});
