describe('library API (dist/index.js)', () => {
  it('exposes every renamed export under its new name and not the old one', async () => {
    expect(existsSync(DIST), 'run npm run build first').toBe(true);
    const api = await import(DIST);
    for (const [old_name, new_name] of Object.entries(RENAMED)) {
      expect(api[new_name], new_name).toBeDefined();
      expect(api[old_name], old_name).toBeUndefined();
    }
  });

  it('exports only snake_case functions, UPPER_CASE constants and the logger', async () => {
    const api = await import(DIST);
    const bad = Object.keys(api).filter((name) => !/^[a-z][a-z0-9_]*$/.test(name) && !/^[A-Z][A-Z0-9_]*$/.test(name));
    expect(bad).toEqual([]);
  });

  it('keeps the logger and constant exports', async () => {
    const api = await import(DIST);
    for (const name of ['logger', 'DOMAINS', 'TIERS', 'REQUIRED_FIELDS', 'DEFAULT_DOCS_ROOT']) expect(api[name], name).toBeDefined();
  });
});
